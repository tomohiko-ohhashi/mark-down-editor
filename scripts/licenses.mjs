// Collects the license texts of everything that ships inside the app (npm
// packages bundled into the UI and Rust crates linked into the binaries) and
// writes them to public/THIRD-PARTY-LICENSES.txt, which is bundled with the
// app and shown from the About dialog. Most of these licenses (MIT, BSD,
// Apache-2.0, ISC ...) require their text to be distributed with the software.
//
//   pnpm update-licenses        (run again whenever dependencies change)
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LICENSE_FILE = /^(licen[sc]e|copying|notice|unlicense)([-._].*)?$/i;

/** License texts found in a package directory (normalised line endings). */
function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n?/g, "\n").trim())
    .filter(Boolean);
}

/** npm packages reachable from the app's runtime dependencies. */
function npmPackages() {
  const seen = new Map();
  const visit = (name, fromDir) => {
    let manifest;
    try {
      manifest = createRequire(join(fromDir, "package.json")).resolve(`${name}/package.json`);
    } catch {
      // No exported package.json: look it up in node_modules directly.
      for (let dir = fromDir; ; dir = dirname(dir)) {
        const candidate = join(dir, "node_modules", name, "package.json");
        if (existsSync(candidate)) {
          manifest = candidate;
          break;
        }
        if (dir === dirname(dir)) return;
      }
    }
    const pkg = JSON.parse(readFileSync(manifest, "utf8"));
    const key = `${pkg.name}@${pkg.version}`;
    if (seen.has(key)) return;
    const dir = dirname(manifest);
    seen.set(key, { name: pkg.name, version: pkg.version, license: licenseName(pkg), texts: licenseTexts(dir), kind: "npm" });
    for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) visit(dep, dir);
  };
  const app = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  for (const dep of Object.keys(app.dependencies ?? {})) visit(dep, root);
  return [...seen.values()];
}

function licenseName(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(" OR ");
  return "(not stated)";
}

/** Rust crates linked into the desktop app and the server (normal and build dependencies, all platforms). */
function cargoPackages() {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: root, maxBuffer: 256 * 1024 * 1024, encoding: "utf8" }),
  );
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const reached = new Set();
  const walk = (id) => {
    if (reached.has(id)) return;
    reached.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((k) => k.kind !== "dev")) walk(dep.pkg);
    }
  };
  meta.workspace_members.forEach(walk);
  return [...reached]
    .filter((id) => !meta.workspace_members.includes(id))
    .map((id) => byId.get(id))
    .map((p) => ({ name: p.name, version: p.version, license: p.license ?? "(not stated)", texts: licenseTexts(dirname(p.manifest_path)), kind: "crate" }));
}

const packages = [...npmPackages(), ...cargoPackages()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// Many packages carry the very same text; print each text once with the packages it covers.
const byText = new Map();
const withoutText = [];
for (const p of packages) {
  if (p.texts.length === 0) withoutText.push(p);
  for (const text of p.texts) byText.set(text, [...(byText.get(text) ?? []), p]);
}
const label = (p) => `${p.name} ${p.version} (${p.kind}, ${p.license})`;
const rule = "=".repeat(78);

let out = `THIRD-PARTY LICENSES

Toucan Markdown Editor includes the software listed below. Each component is covered
by its own license; the texts follow the list. This file is generated by
scripts/licenses.mjs (pnpm update-licenses).

${packages.length} components
${packages.map((p) => `  - ${label(p)}`).join("\n")}
`;
if (withoutText.length > 0) {
  out += `\n${rule}\nThe following components ship no license file of their own; the license named\nin their package metadata applies:\n\n${withoutText.map((p) => `  - ${label(p)}`).join("\n")}\n`;
}
for (const [text, users] of [...byText].sort((a, b) => b[1].length - a[1].length)) {
  const names = [...new Set(users.map(label))];
  out += `\n${rule}\n${names.join("\n")}\n${rule}\n\n${text}\n`;
}

mkdirSync(join(root, "public"), { recursive: true });
writeFileSync(join(root, "public", "THIRD-PARTY-LICENSES.txt"), out);
console.log(`${packages.length} components (${packages.filter((p) => p.kind === "npm").length} npm, ${packages.filter((p) => p.kind === "crate").length} crates), ${byText.size} distinct license texts, ${withoutText.length} without a license file`);
console.log(`wrote public/THIRD-PARTY-LICENSES.txt (${Math.round(out.length / 1024)} KB)`);
